"""
City Cultural Pulse — analyzer
Reads collected CSVs and scores queries by trend velocity.
Outputs a weekly report: top rising topics per domain.
Supports single-city reports and cross-city comparisons.

Usage:
    python3 analyze.py --city berlin
    python3 analyze.py --city new_york --weeks 6
    python3 analyze.py --compare           # cross-city comparison across all three
"""

import argparse
from pathlib import Path
from datetime import datetime, timezone

import pandas as pd
import numpy as np

from config import CITIES

REPORTS_DIR = Path("reports")
REPORTS_DIR.mkdir(exist_ok=True)


# ── Loading ───────────────────────────────────────────────────────────────────

def load_trends(path: Path) -> pd.DataFrame:
    """
    Reads a cumulative trends file, keeping only anchored Google Trends rows
    (older unanchored and dry-run rows aren't on a comparable scale).
    Adds relative_interest: the query's interest as a % of the anchor term's
    interest in the same batch and week (100 = as searched as the anchor).
    """
    df = pd.read_csv(path)
    if "anchor_score" not in df.columns:
        return pd.DataFrame()
    df = df[df["source"] == "google_trends_anchored"].copy()
    df["relative_interest"] = 100 * df["interest_score"] / df["anchor_score"].replace(0, np.nan)
    return df.dropna(subset=["relative_interest"])


# ── Trend scoring ─────────────────────────────────────────────────────────────

def compute_trend_scores(
    df: pd.DataFrame, lookback_weeks: int = 4, normalize: bool = True
) -> pd.DataFrame:
    """
    For each query, compute (on anchor-relative interest):
      - velocity: average week-over-week change in interest
      - acceleration: change in velocity (is it speeding up?)
      - trend_score: composite (velocity * 0.6 + acceleration * 0.4), normalized 0–100

    A high score = interest rising AND accelerating. Pass normalize=False to get
    raw metrics, e.g. to normalize several cities together with add_trend_score.
    """
    if df.empty:
        return pd.DataFrame()

    df = df.copy()
    df["week_dt"] = pd.to_datetime(df["week"] + "-1", format="%Y-%W-%w")
    df = df.sort_values(["domain", "query", "week_dt"])

    results = []

    for (domain, query), group in df.groupby(["domain", "query"]):
        group = group.set_index("week_dt")["relative_interest"].resample("W").mean().fillna(0)

        if len(group) < 2:
            continue

        recent = group.tail(lookback_weeks)
        diffs = recent.diff().dropna()

        velocity     = diffs.mean()
        acceleration = diffs.diff().dropna().mean() if len(diffs) > 1 else 0.0
        latest_score = recent.iloc[-1]

        results.append({
            "domain": domain,
            "query": query,
            "latest_interest": round(latest_score, 1),
            "velocity": round(velocity, 2),
            "acceleration": round(float(acceleration), 2) if not np.isnan(acceleration) else 0.0,
            "weeks_of_data": len(group),
        })

    if not results:
        return pd.DataFrame()

    out = pd.DataFrame(results)
    return add_trend_score(out) if normalize else out


def add_trend_score(out: pd.DataFrame) -> pd.DataFrame:
    """Min-max normalizes velocity/acceleration across all rows given, then scores."""
    out = out.copy()
    for col in ["velocity", "acceleration"]:
        col_min, col_max = out[col].min(), out[col].max()
        if col_max > col_min:
            out[f"{col}_norm"] = (out[col] - col_min) / (col_max - col_min) * 100
        else:
            out[f"{col}_norm"] = 50.0

    out["trend_score"] = (out["velocity_norm"] * 0.6 + out["acceleration_norm"] * 0.4).round(1)

    return out.sort_values("trend_score", ascending=False)


# ── Single-city report ────────────────────────────────────────────────────────

def generate_report(city_key: str, trend_scores: pd.DataFrame) -> str:
    display  = CITIES[city_key]["display_name"]
    week_tag = datetime.now(timezone.utc).strftime("Week %W, %Y")

    lines = [
        f"{display.upper()} CULTURAL PULSE — {week_tag}",
        "=" * 55,
        "",
        "TOP RISING QUERIES (by trend score)",
        "-" * 40,
    ]

    for domain in ["tech", "culture", "fashion", "food", "travel"]:
        domain_df = trend_scores[trend_scores["domain"] == domain].head(5)
        if domain_df.empty:
            continue
        lines.append(f"\n{domain.upper()}")
        for _, row in domain_df.iterrows():
            arrow = "↑↑" if row["acceleration"] > 0 else "↑"
            lines.append(
                f"  {arrow} {row['query']:<40} score: {row['trend_score']:.0f}  "
                f"(v={row['velocity']:+.1f}, a={row['acceleration']:+.1f})"
            )

    lines += [
        "",
        "=" * 55,
        f"Generated by {display} Cultural Pulse",
        "",
        "LINKEDIN POST DRAFT",
        "-" * 40,
    ]

    top = trend_scores.iloc[0] if not trend_scores.empty else None
    if top is not None:
        lines.append(f"""
This week in {display}'s cultural search landscape:

The fastest-rising topic I'm tracking: "{top['query']}" (+{top['velocity']:.0f} pts/week, accelerating).

I'm building a question prediction model that uses search velocity to forecast
which topics will peak before they go mainstream — tracking Berlin, New York,
and Paris in parallel to see how city identity shows up in search behaviour.

Curious: what would make this useful to you?

#CulturalPulse #{display.replace(' ', '')} #TrendResearch #StartupScene #DataScience
""")

    return "\n".join(lines)


# ── Cross-city comparison report ──────────────────────────────────────────────

def generate_comparison_report(all_scores: dict) -> str:
    """
    all_scores: {city_key: trend_scores_df}
    Compares top queries per domain across all three cities.
    """
    week_tag = datetime.now(timezone.utc).strftime("Week %W, %Y")

    lines = [
        f"CITY CULTURAL PULSE — CROSS-CITY COMPARISON — {week_tag}",
        "=" * 65,
        "",
    ]

    for domain in ["tech", "culture", "fashion", "food", "travel"]:
        lines.append(f"\n{domain.upper()}")
        lines.append("-" * 40)

        for city_key, scores in all_scores.items():
            display   = CITIES[city_key]["display_name"]
            domain_df = scores[scores["domain"] == domain].head(3)
            if domain_df.empty:
                continue
            lines.append(f"\n  {display}:")
            for _, row in domain_df.iterrows():
                lines.append(
                    f"    ↑ {row['query']:<38} score: {row['trend_score']:.0f}"
                )

    lines += [
        "",
        "=" * 65,
        "Generated by City Cultural Pulse",
    ]

    return "\n".join(lines)


# ── Entry point ───────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--city", choices=list(CITIES.keys()), help="Single city to analyze")
    parser.add_argument("--compare", action="store_true", help="Cross-city comparison")
    parser.add_argument("--weeks", type=int, default=4, help="Lookback window for trend scoring")
    args = parser.parse_args()

    if not args.city and not args.compare:
        parser.error("Provide --city <city> or --compare")

    week_tag = datetime.now(timezone.utc).strftime("%Y-W%W")

    if args.compare:
        print("City Cultural Pulse — cross-city comparison")
        raw = []

        for city_key in CITIES:
            trends_path = Path("data") / city_key / "trends_all.csv"
            if not trends_path.exists():
                print(f"  No data for {city_key}, skipping")
                continue
            df     = load_trends(trends_path)
            scores = compute_trend_scores(df, lookback_weeks=args.weeks, normalize=False)
            if not scores.empty:
                raw.append(scores.assign(city=city_key))

        if not raw:
            print("\nNo data found for any city. Run collect.py --test first.")
            return

        # Normalize all cities together, so a score means the same thing in each
        combined   = add_trend_score(pd.concat(raw, ignore_index=True))
        all_scores = {}
        for city_key, scores in combined.groupby("city", sort=False):
            all_scores[city_key] = scores
            scores.to_csv(
                REPORTS_DIR / f"trend_scores_{city_key}_{week_tag}.csv", index=False
            )

        report      = generate_comparison_report(all_scores)
        report_path = REPORTS_DIR / f"comparison_report_{week_tag}.txt"
        report_path.write_text(report)
        print("\n" + report)
        print(f"\nReport saved to {report_path}")

    else:
        display     = CITIES[args.city]["display_name"]
        trends_path = Path("data") / args.city / "trends_all.csv"

        print(f"City Cultural Pulse — analyzer ({display})")

        if not trends_path.exists():
            print(f"\nNo data found at {trends_path}.")
            print(f"Run `python3 collect.py --city {args.city} --test` first.")
            return

        df     = load_trends(trends_path)
        scores = compute_trend_scores(df, lookback_weeks=args.weeks)

        if scores.empty:
            print("\nNot enough data yet. You need at least 2 weeks. Run collect.py again next week.")
            return

        scores_path = REPORTS_DIR / f"trend_scores_{args.city}_{week_tag}.csv"
        scores.to_csv(scores_path, index=False)
        print(f"\nTrend scores saved to {scores_path}")

        report      = generate_report(args.city, scores)
        report_path = REPORTS_DIR / f"weekly_report_{args.city}_{week_tag}.txt"
        report_path.write_text(report)

        print("\n" + report)
        print(f"\nReport saved to {report_path}")


if __name__ == "__main__":
    main()
